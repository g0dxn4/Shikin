import { readFile, readdir, writeFile, mkdir, mkdtemp } from 'node:fs/promises'
import { rmSync } from 'node:fs'
import { resolve, relative, join } from 'node:path'
import { tmpdir } from 'node:os'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.includes('--check')
const allowed = new Set(['--check'])
if (process.argv.slice(2).some((arg) => !allowed.has(arg)))
  throw new Error('Usage: generate-mcp-inventory.mjs [--check]')
// Catalog inspection never opens the financial database. Isolate plugin discovery
// before importing the registry, including on platforms without XDG data roots.
const syntheticRoot = await mkdtemp(join(tmpdir(), 'shikin-mcp-inventory-'))
process.once('exit', () => rmSync(syntheticRoot, { recursive: true, force: true }))
process.env.SHIKIN_EXTENSIONS_DIR = join(syntheticRoot, 'extensions')
await mkdir(process.env.SHIKIN_EXTENSIONS_DIR)
const [
  { builtInTools },
  { createProgram },
  { inspectMcpCatalog },
  { CORE_MCP_TOOL_NAMES, isReadOnlyMcpTool },
] = await Promise.all([
  import('../cli/src/tools.ts'),
  import('../cli/src/cli.ts'),
  import('../cli/src/mcp-inventory.ts'),
  import('../cli/src/mcp-profiles.ts'),
])
async function files(directory) {
  const entries = await readdir(directory, { withFileTypes: true })
  return (
    await Promise.all(
      entries.map((entry) =>
        entry.isDirectory()
          ? files(resolve(directory, entry.name))
          : [resolve(directory, entry.name)]
      )
    )
  ).flat()
}
const sourceFiles = (await files(resolve(root, 'cli/src'))).filter(
  (path) => path.endsWith('.ts') && !path.includes('.test.') && !path.includes('/fixtures/')
)
const sources = await Promise.all(
  sourceFiles.map(async (path) => ({
    path: relative(root, path),
    text: await readFile(path, 'utf8'),
  }))
)
const documentationFiles = (
  await Promise.all(['docs', 'skills'].map((folder) => files(resolve(root, folder))))
)
  .flat()
  .filter((path) => path.endsWith('.md') && !path.includes('MCP-TOOL-INVENTORY'))
const documentation = await Promise.all(documentationFiles.map((path) => readFile(path, 'utf8')))
const listed = await inspectMcpCatalog()
const definitions = new Map(builtInTools.map((tool) => [tool.name, tool]))
const tools = listed.catalog.tools.map((wireTool) => {
  const definition = definitions.get(wireTool.name)
  const pattern = new RegExp(`\\bname:\\s*['"]${wireTool.name}['"]`)
  const implementation = sources
    .filter((source) => pattern.test(source.text))
    .map((source) => source.path)
  return {
    ...wireTool,
    implementation,
    primary: CORE_MCP_TOOL_NAMES.includes(wireTool.name),
    readOnlyEligible: isReadOnlyMcpTool(definition),
    effects: definition.effects ?? null,
    effectsAudited: definition.effects !== undefined,
    cliUnavailableMessage: definition.cliUnavailableMessage ?? null,
    mcpUnavailableMessage: definition.mcpUnavailableMessage ?? null,
    documented: documentation.some((text) => text.includes(wireTool.name)),
  }
})
const commands = createProgram(builtInTools)
  .commands.map((command) => command.name())
  .sort()
const inventory = {
  schemaVersion: 'shikin.mcp-inventory.v1',
  generatedFrom: 'cli/src/tools/index.ts via the actual MCP tools/list response',
  toolCount: tools.length,
  commandCount: commands.length,
  coreToolCount: tools.filter((tool) => tool.primary).length,
  readOnlyToolCount: tools.filter((tool) => tool.readOnlyEligible).length,
  note: 'Effects not declared are unaudited, never implicitly read-only. Documentation references are not runtime usage telemetry.',
  tools,
  commands,
}
const escape = (value) => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ')
const markdown = `# Generated MCP tool inventory

Generated by \`pnpm inventory:generate\`. Do not edit by hand. \`pnpm inventory:check\` detects drift.

**${inventory.toolCount} built-in tools / ${inventory.commandCount} CLI commands / ${inventory.coreToolCount} core MCP tools / ${inventory.readOnlyToolCount} audited read-only tools.**

The full MCP profile and CLI preserve every built-in tool below. Core is opt-in. Enabled local plugins are additional and excluded from these reproducible counts. The [JSON inventory](MCP-TOOL-INVENTORY.json) contains every actual input schema, annotation, declared effect, implementation path and documentation-presence flag. No production usage telemetry was collected.

“Unaudited” means that no effects declaration exists; the read-only profile excludes it. “Write/other” includes explicit effects with no read-only guarantee. See [architecture and redundancy analysis](../research/MCP-DESIGN.md) for workflow decisions.

| Tool | Core | Permission | Writes to | Implementation | Purpose |
| --- | --- | --- | --- | --- | --- |
${tools.map((tool) => `| \`${tool.name}\` | ${tool.primary ? 'Yes' : ''} | ${tool.readOnlyEligible ? 'Read-only' : tool.effectsAudited ? 'Write/other' : 'Unaudited'} | ${escape(tool.effects?.writesTo?.join(', ') ?? 'Not declared')} | ${tool.implementation.map((path) => `[${path}](../../${path})`).join(', ')} | ${escape(tool.description ?? '')} |`).join('\n')}
`
const outputs = new Map([
  ['docs/reference/MCP-TOOL-INVENTORY.json', `${JSON.stringify(inventory, null, 2)}\n`],
  ['docs/reference/MCP-TOOL-INVENTORY.md', markdown],
  [
    'cli/src/fixtures/public-automation-inventory.json',
    `${JSON.stringify({ tools: tools.map((tool) => tool.name), commands }, null, 2)}\n`,
  ],
])
let stale = false
for (const [path, content] of outputs) {
  if (check) {
    const actual = await readFile(resolve(root, path), 'utf8').catch(() => '')
    if (actual !== content) {
      console.error(`Stale generated inventory: ${path}`)
      stale = true
    }
  } else {
    await mkdir(resolve(root, path, '..'), { recursive: true })
    await writeFile(resolve(root, path), content)
  }
}
if (stale) process.exitCode = 1
else
  console.log(
    `${check ? 'Verified' : 'Generated'} ${tools.length} tools, ${commands.length} CLI commands, ${inventory.coreToolCount} core tools.`
  )
