async function capturePartitionWitnesses() {
  const commands: Array<{ name: string; input: Record<string, unknown>; result: unknown }> = []
  const run = async (name: string, input: Record<string, unknown> = {}) => {
    const tool = builtInTools.find((candidate) => candidate.name === name)!
    let result
    try {
      result = await tool.execute(tool.schema.parse(input))
    } catch (error) {
      result = { thrown: error instanceof Error ? error.message : String(error) }
    }
    commands.push({ name, input, result })
    return result
  }
  const first = await run('query-transactions', { limit: 1 })
  await run('query-transactions', { limit: 1, cursor: first.nextCursor })
  await run('query-transactions', { limit: 1, cursor: `${first.nextCursor}=` })
  await run('query-transactions', { limit: 1, cursor: first.nextCursor, type: 'income' })
  state.db.exec('UPDATE app_data_state SET data_revision=38 WHERE id=1')
  await run('query-transactions', { limit: 1, cursor: first.nextCursor, type: 'income' })
  state.db.exec("UPDATE app_data_state SET database_id='other',data_revision=37 WHERE id=1")
  await run('query-transactions', { limit: 1, cursor: first.nextCursor })
  state.db.exec("UPDATE app_data_state SET database_id='partition-parent' WHERE id=1")
  await run('list-tags')
  await run('list-placeholder-transactions')
  await run('get-spending-summary', { start: '2026-05-01', end: '2026-05-31', currency: 'USD' })
  await run('get-spending-summary', {
    start: '2026-05-01',
    end: '2026-05-31',
    currency: 'USD',
    basis: 'net_consumption',
  })
  await run('finance-sanity-check')
  await run('automation-context', { redacted: true })
  await run('audit-list', { redacted: true })
  await run('audit-show', { id: 'audit', redacted: false })
  for (const format of ['json', 'csv', 'markdown'])
    for (const redacted of [false, true]) await run('export-data', { format, redacted })
  state.db.exec('DROP TABLE subscriptions')
  await run('export-data')
  state.db.exec('ALTER TABLE accounts RENAME COLUMN balance TO missing_balance')
  await run('export-data')
  const tables = state.db
    .prepare(
      "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
    )
    .all() as Array<{ name: string }>
  const dump = Object.fromEntries(
    tables.map(({ name }) => [
      name,
      state.db.prepare(`SELECT * FROM "${name}" ORDER BY rowid`).all(),
    ])
  )
  return { commands, trace: state.trace, dump }
}

