#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import {
  normalizeSqlDefinition,
  readCurrentTableManifest,
  tokenizeSql,
} from './sqlite-schema-validation.mjs'

export { normalizeSqlDefinition, readCurrentTableManifest } from './sqlite-schema-validation.mjs'

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url))
const DEFAULT_ROOT = resolve(SCRIPT_DIR, '..')

export function extractStringArrayConstant(source, constantName) {
  const initializer = extractInitializer(source, constantName, '[')
  return [...initializer.matchAll(/'([^']+)'/g)].map((match) => match[1])
}

export function extractStringArrayMapConstant(source, constantName) {
  const initializer = extractInitializer(source, constantName, '{')
  const result = {}
  for (const match of initializer.matchAll(/([A-Za-z_][A-Za-z0-9_]*):\s*\[([\s\S]*?)\]/g)) {
    result[match[1]] = [...match[2].matchAll(/'([^']+)'/g)].map((item) => item[1])
  }
  return result
}

export function readSchemaContract(rootDir = DEFAULT_ROOT) {
  return JSON.parse(readFileSync(join(rootDir, 'schema/shikin-contract.json'), 'utf8'))
}

export function renderSchemaContractIdentity(rawContractBytes, contract) {
  const rawBytesSha256 = createHash('sha256').update(rawContractBytes).digest('hex')
  const latestMigration = contract.latestMigration.replaceAll('\\', '\\\\').replaceAll("'", "\\'")
  return `// Generated by scripts/generate-current-schema-contract.mjs. Do not edit.\nexport const SHIKIN_SCHEMA_CONTRACT_IDENTITY = Object.freeze({\n  rawBytesSha256: 'sha256:${rawBytesSha256}',\n  contractVersion: ${JSON.stringify(contract.contractVersion)},\n  latestMigration: '${latestMigration}',\n})\n`
}

export function validateSchemaContract(rootDir = DEFAULT_ROOT) {
  const errors = []
  const rawContractBytes = readFileSync(join(rootDir, 'schema/shikin-contract.json'))
  const contract = JSON.parse(rawContractBytes.toString('utf8'))
  const lockContract = JSON.parse(
    readFileSync(join(rootDir, 'schema/database-operation-lock-v1.json'), 'utf8')
  )
  const guiSource = readFileSync(join(rootDir, 'src/lib/database.ts'), 'utf8')
  const serverSource = readFileSync(join(rootDir, 'scripts/data-server.mjs'), 'utf8')
  const cliMigrationSource = readFileSync(join(rootDir, 'cli/src/migrations.ts'), 'utf8')
  const cliDatabaseSource = readFileSync(join(rootDir, 'cli/src/database.ts'), 'utf8')
  const schemaIdentityPath = join(rootDir, 'scripts/shikin-schema-contract-identity.mjs')
  let generatedSchemaIdentity = null
  try {
    generatedSchemaIdentity = readFileSync(schemaIdentityPath, 'utf8')
  } catch (error) {
    errors.push(`trusted schema identity is unreadable: ${error.message}`)
  }
  const expectedSchemaIdentity = renderSchemaContractIdentity(rawContractBytes, contract)
  if (generatedSchemaIdentity !== null && generatedSchemaIdentity !== expectedSchemaIdentity) {
    errors.push('trusted schema identity drifted from raw schema/shikin-contract.json bytes')
  }

  const adapterMigrations = {
    'src/lib/database.ts': extractStringArrayConstant(guiSource, 'CURRENT_SHIKIN_MIGRATIONS'),
    'scripts/data-server.mjs': extractStringArrayConstant(
      serverSource,
      'CURRENT_SHIKIN_MIGRATIONS'
    ),
    'cli/src/migrations.ts': extractStringArrayConstant(
      cliMigrationSource,
      'CLI_DATABASE_MIGRATIONS'
    ),
  }
  for (const [adapter, migrations] of Object.entries(adapterMigrations)) {
    compare(errors, `${adapter} migration names`, migrations, contract.migrationNames)
  }

  const guiCurrentTables = extractStringArrayMapConstant(guiSource, 'CURRENT_SHIKIN_SCHEMA')
  const serverCurrentTables = extractStringArrayMapConstant(serverSource, 'CURRENT_SHIKIN_SCHEMA')
  compare(
    errors,
    'GUI current readiness tables',
    guiCurrentTables,
    contract.readiness.gui.currentTables
  )
  compare(
    errors,
    'browser data-server current readiness tables',
    serverCurrentTables,
    contract.readiness.dataServer.currentTables
  )
  compare(
    errors,
    'GUI and browser data-server current readiness parity',
    guiCurrentTables,
    serverCurrentTables
  )
  compare(
    errors,
    'GUI import minimum readiness tables',
    extractStringArrayMapConstant(guiSource, 'REQUIRED_SHIKIN_TABLES'),
    contract.readiness.gui.importMinimumTables
  )

  compare(
    errors,
    'CLI core tables',
    extractStringArrayConstant(cliDatabaseSource, 'REQUIRED_CORE_TABLES'),
    contract.readiness.cli.coreTables
  )
  compare(
    errors,
    'CLI core columns',
    extractStringArrayMapConstant(cliDatabaseSource, 'REQUIRED_CORE_SCHEMA'),
    contract.readiness.cli.coreColumns
  )
  compare(
    errors,
    'CLI QOL columns',
    extractStringArrayMapConstant(cliDatabaseSource, 'REQUIRED_CLI_QOL_SCHEMA'),
    contract.readiness.cli.cliQolColumns
  )
  compare(
    errors,
    'CLI credit-card metadata repair columns',
    extractStringArrayConstant(cliDatabaseSource, 'CREDIT_CARD_COLUMNS'),
    contract.readiness.cli.creditCardColumns
  )

  const migrationFileNames = readdirSync(join(rootDir, 'src-tauri/migrations'))
    .filter((name) => name.endsWith('.sql'))
    .sort()
  const migrationFiles = migrationFileNames.map((name) => name.slice(0, -4))
  compare(errors, 'src-tauri schema-history files', migrationFiles, contract.migrationSqlFiles)
  if (contract.latestMigration !== contract.migrationNames.at(-1)) {
    errors.push('latestMigration must equal the final migrationNames entry')
  }
  if (contract.migrationNames.some((name) => name.startsWith('020_'))) {
    errors.push('Milestone 2 contract must not contain migration 020')
  }

  validateCurrentSchemaManifest(errors, contract.currentSchema)
  compare(
    errors,
    'current schema table names',
    contract.currentSchema.tables.map((table) => table.name),
    Object.keys(contract.readiness.gui.currentTables).sort()
  )

  const allowedObjects = [
    ...contract.allowedSchemaObjects.indexes,
    ...contract.allowedSchemaObjects.triggers,
    ...contract.allowedSchemaObjects.views,
  ]
  const allowedNames = new Set(allowedObjects.map((object) => object.name))
  if (allowedNames.size !== allowedObjects.length) {
    errors.push('allowedSchemaObjects contains duplicate names')
  }
  for (const object of allowedObjects) {
    if (normalizeSqlDefinition(object.sql) !== object.sql) {
      errors.push(`allowed schema object ${object.name} does not contain normalized SQL`)
    }
  }

  const expectedDefinitions = new Map(allowedObjects.map((object) => [object.name, object.sql]))
  const adapterObjects = {
    'scripts/data-server.mjs': collectSchemaObjectDefinitions(serverSource),
    'src/lib/database.ts': collectSchemaObjectDefinitions(guiSource),
  }
  for (const [adapter, objects] of Object.entries(adapterObjects)) {
    for (const name of allowedNames) {
      if (!objects.has(name)) {
        errors.push(`allowed schema object ${name} is absent from ${adapter}`)
      } else if (objects.get(name) !== expectedDefinitions.get(name)) {
        errors.push(`${adapter} schema object ${name} drifted from its normalized definition`)
      }
    }
    for (const name of objects.keys()) {
      if (!allowedNames.has(name)) {
        errors.push(`${adapter} creates uncontracted schema object ${name}`)
      }
    }
  }

  validateLockContract(errors, lockContract)

  compare(
    errors,
    'migration schema-history object mapping keys',
    Object.keys(contract.migrationSchemaObjects).sort(),
    migrationFiles
  )
  for (const migrationFile of migrationFiles) {
    const source = readFileSync(
      join(rootDir, 'src-tauri/migrations', `${migrationFile}.sql`),
      'utf8'
    )
    const actualObjects = collectSchemaObjectDefinitions(source)
    const expectedNamesByType = contract.migrationSchemaObjects[migrationFile]
    if (!expectedNamesByType) continue
    const expectedNames = [
      ...expectedNamesByType.indexes,
      ...expectedNamesByType.triggers,
      ...expectedNamesByType.views,
    ]
    compareSchemaObjectSets(
      errors,
      `src-tauri/migrations/${migrationFile}.sql`,
      actualObjects,
      expectedNames,
      expectedDefinitions
    )
  }

  return { contract, errors }
}

export function isDirectExecution(importMetaUrl, argvPath = process.argv[1]) {
  return Boolean(argvPath) && pathToFileURL(resolve(argvPath)).href === importMetaUrl
}

function extractInitializer(source, constantName, openingCharacter) {
  const declarationPattern = new RegExp(`\\bconst\\s+${escapeRegExp(constantName)}\\b`)
  const declaration = declarationPattern.exec(source)
  if (!declaration) throw new Error(`Could not locate const ${constantName}`)
  const equalsIndex = source.indexOf('=', declaration.index + declaration[0].length)
  const openingIndex = source.indexOf(openingCharacter, equalsIndex + 1)
  if (equalsIndex === -1 || openingIndex === -1) {
    throw new Error(`Could not locate ${constantName} initializer`)
  }
  return readBalanced(source, openingIndex)
}

function readBalanced(source, startIndex) {
  const opening = source[startIndex]
  const closing = opening === '[' ? ']' : opening === '{' ? '}' : null
  if (!closing) throw new Error(`Unsupported initializer delimiter ${opening}`)

  let depth = 0
  let quote = null
  let escaped = false
  for (let index = startIndex; index < source.length; index += 1) {
    const character = source[index]
    if (quote) {
      if (escaped) escaped = false
      else if (character === '\\') escaped = true
      else if (character === quote) quote = null
      continue
    }
    if (character === "'" || character === '"' || character === '`') {
      quote = character
      continue
    }
    if (character === opening) depth += 1
    if (character === closing) depth -= 1
    if (depth === 0) return source.slice(startIndex, index + 1)
  }
  throw new Error(`Unterminated ${opening} initializer`)
}

export function collectSchemaObjectDefinitions(source) {
  const definitions = new Map()
  const searchableSource = maskSqlComments(source)
  const pattern =
    /\bCREATE\s+(?:UNIQUE\s+)?(INDEX|TRIGGER|VIEW)\s+(?:IF\s+NOT\s+EXISTS\s+)?([A-Za-z_][A-Za-z0-9_]*)/gi
  for (const match of searchableSource.matchAll(pattern)) {
    const type = match[1].toUpperCase()
    const start = match.index
    const end = sqlDefinitionEnd(source, start, type === 'TRIGGER')
    if (end === -1) throw new Error(`Could not read schema object ${match[2]} from source`)
    const definition = normalizeSqlDefinition(source.slice(start, end))
    const previous = definitions.get(match[2])
    if (previous && previous !== definition) {
      throw new Error(`Source contains conflicting definitions for schema object ${match[2]}`)
    }
    definitions.set(match[2], definition)
  }
  return definitions
}

function sqlDefinitionEnd(source, start, isTrigger) {
  const sourceStringDelimiter = ["'", '"', '`'].includes(source[start - 1])
    ? source[start - 1]
    : '`'
  const tokens = tokenizeSql(source.slice(start), {
    includePositions: true,
    stopAtDelimiter: sourceStringDelimiter,
  })
  for (let index = 0; index < tokens.length; index += 1) {
    const token = tokens[index]
    if (token.value === sourceStringDelimiter) {
      if (!isTrigger || tokens[index - 1]?.value === 'end') return start + token.start
      continue
    }
    if (token.value !== ';') continue
    if (!isTrigger || tokens[index - 1]?.value === 'end') return start + token.end
  }
  return -1
}

function maskSqlComments(source) {
  const masked = [...source]
  let quote = null
  for (let index = 0; index < source.length; index += 1) {
    const character = source[index]
    const next = source[index + 1]
    if (quote) {
      if (character === quote) {
        if (next === quote) index += 1
        else quote = null
      }
      continue
    }
    if (character === "'" || character === '"' || character === '[') {
      quote = character === '[' ? ']' : character
      continue
    }
    let end = -1
    if ((character === '-' && next === '-') || (character === '/' && next === '/')) {
      end = source.indexOf('\n', index + 2)
      if (end === -1) end = source.length
    } else if (character === '/' && next === '*') {
      const closing = source.indexOf('*/', index + 2)
      end = closing === -1 ? source.length : closing + 2
    }
    if (end === -1) continue
    for (let commentIndex = index; commentIndex < end; commentIndex += 1) {
      if (masked[commentIndex] !== '\n' && masked[commentIndex] !== '\r') {
        masked[commentIndex] = ' '
      }
    }
    index = end - 1
  }
  return masked.join('')
}

function compareSchemaObjectSets(errors, label, actualObjects, expectedNames, expectedDefinitions) {
  const actualNames = [...actualObjects.keys()].sort()
  const expectedSorted = [...expectedNames].sort()
  const expectedSet = new Set(expectedSorted)
  const actualSet = new Set(actualNames)
  const missing = expectedSorted.filter((name) => !actualSet.has(name))
  const unexpected = actualNames.filter((name) => !expectedSet.has(name))
  if (missing.length > 0) errors.push(`${label} is missing schema objects: ${missing.join(', ')}`)
  if (unexpected.length > 0) {
    errors.push(`${label} contains unexpected schema objects: ${unexpected.join(', ')}`)
  }
  for (const name of expectedSorted.filter((item) => actualSet.has(item))) {
    if (actualObjects.get(name) !== expectedDefinitions.get(name)) {
      errors.push(`${label} schema object ${name} drifted from its normalized definition`)
    }
  }
}

function validateCurrentSchemaManifest(errors, currentSchema) {
  if (!currentSchema || !Array.isArray(currentSchema.tables)) {
    errors.push('currentSchema.tables must be an array')
    return
  }
  const names = new Set()
  for (const table of currentSchema.tables) {
    if (names.has(table.name)) errors.push(`currentSchema contains duplicate table ${table.name}`)
    names.add(table.name)
    if (normalizeSqlDefinition(table.sql) !== table.sql) {
      errors.push(`current table ${table.name} does not contain normalized CREATE TABLE SQL`)
    }
    if (
      table.schema !== 'main' ||
      table.type !== 'table' ||
      !Array.isArray(table.columns) ||
      !Array.isArray(table.autoIndexes) ||
      !table.tableList
    ) {
      errors.push(`current table ${table.name} has malformed structural metadata`)
    }
  }
  const sorted = [...currentSchema.tables].map((table) => table.name).sort()
  if (stableJson([...currentSchema.tables].map((table) => table.name)) !== stableJson(sorted)) {
    errors.push('currentSchema.tables must be deterministically sorted by name')
  }
}

function validateLockContract(errors, lockContract) {
  if (
    lockContract['x-shikin-protocol'] !== 'shikin.database-operation-lock' ||
    lockContract['x-shikin-version'] !== 1
  ) {
    errors.push('database operation lock protocol identity must remain at version 1')
  }
  if (
    lockContract.discriminator?.propertyName !== 'recordKind' ||
    !Array.isArray(lockContract.oneOf) ||
    lockContract.oneOf.length < 2
  ) {
    errors.push('database operation lock contract must have a discriminated root oneOf')
  }
  for (const shape of [
    'operationStateRecord',
    'registrationMutexRecord',
    'runtimeLease',
    'exclusiveIntent',
  ]) {
    if (!lockContract.$defs?.[shape]) {
      errors.push(`database operation lock contract is missing the ${shape} record shape`)
    }
  }
  const timing = lockContract['x-shikin-timing-constraints']
  if (
    !timing ||
    !(timing.registrationMutexTtlMs?.minimum > 0) ||
    !(timing.registrationMutexTtlMs?.maximum >= timing.registrationMutexTtlMs?.minimum) ||
    !(timing.runtimeLeaseTtlMs?.minimum > 0) ||
    !(timing.runtimeLeaseTtlMs?.maximum >= timing.runtimeLeaseTtlMs?.minimum) ||
    !(timing.heartbeatIntervalMs?.minimum > 0) ||
    !(timing.heartbeatMustBeLessThanTtlFraction > 0) ||
    !(timing.heartbeatMustBeLessThanTtlFraction < 1)
  ) {
    errors.push('database operation lock TTL and heartbeat constraints are invalid')
  }
  const transitions = lockContract['x-shikin-transitions']
  if (!Array.isArray(transitions) || transitions.length === 0) {
    errors.push('database operation lock contract must declare protocol transitions')
  }
  const safetyInvariants = lockContract['x-shikin-safety-invariants']
  if (!Array.isArray(safetyInvariants) || safetyInvariants.length === 0) {
    errors.push('database operation lock contract must declare safety invariants')
  }
}

function compare(errors, label, actual, expected) {
  if (stableJson(actual) !== stableJson(expected)) {
    errors.push(`${label} drifted from schema/shikin-contract.json`)
  }
}

function stableJson(value) {
  if (Array.isArray(value)) return JSON.stringify(value.map(stableValue))
  return JSON.stringify(stableValue(value))
}

function stableValue(value) {
  if (Array.isArray(value)) return value.map(stableValue)
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value)
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([key, item]) => [key, stableValue(item)])
    )
  }
  return value
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

if (isDirectExecution(import.meta.url)) {
  const { errors } = validateSchemaContract()
  if (errors.length > 0) {
    for (const error of errors) console.error(`❌ ${error}`)
    process.exitCode = 1
  } else {
    console.log('✅ Schema contract matches GUI, browser data-server, CLI, and Tauri sources')
  }
}
